    public levels(String username) {
        initComponents();
        this.username = username; // Kullanıcı adını kaydet
        Random random = new Random();
        int trap1 = random.nextInt(30);
        int trap2;
        do {
            trap2 = random.nextInt(30);
        } while (trap2 == trap1);

        String[] otherTypes = {"treasure", "empty"};
        cellNode prev = null;
        head = null;
        // 30 butonun her biri için bir node oluştur
        JButton[] buttons = {
            jButton2, jButton3, jButton4, jButton5,
            jButton6, jButton7, jButton8, jButton9, jButton10,
            jButton11, jButton12, jButton13, jButton14, jButton15,
            jButton16, jButton17, jButton18, jButton19, jButton20,
            jButton21, jButton22, jButton23, jButton24, jButton25,
            jButton26, jButton27, jButton28, jButton29, jButton30
        }; // Tüm butonları sırayla ekle

        for (int i = 0; i < 29; i++) {
            String cellType;
            if (i == trap1 || i == trap2) {
                cellType = "trap";
            } else {
                cellType = otherTypes[random.nextInt(otherTypes.length)];
            }
            cellNode node = new cellNode(buttons[i], cellType);
            // Renk ata
            if (cellType.equals("treasure")) {
                node.button.setBackground(java.awt.Color.YELLOW);
            } else if (cellType.equals("trap")) {
                node.button.setBackground(java.awt.Color.RED);
            } else {
                node.button.setBackground(java.awt.Color.LIGHT_GRAY);
            }

            if (head == null) {
                head = node;
            }
            if (prev != null) {
                prev.next = node;
            }
            prev = node;
        }
        current = head;
        current.button.setBackground(java.awt.Color.GREEN);

    }

