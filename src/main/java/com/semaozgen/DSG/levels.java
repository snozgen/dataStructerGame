    private void btn_rollDiceActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_rollDiceActionPerformed
        // TODO add your handling code here:
// Eski konumun rengini geri döndür
        if (current.cellType.equals("treasure")) {
            current.button.setBackground(java.awt.Color.YELLOW);
        } else if (current.cellType.equals("trap")) {
            current.button.setBackground(java.awt.Color.RED);
        } else {
            current.button.setBackground(java.awt.Color.LIGHT_GRAY);
        }

        // Zar at
        Random random = new Random();
        int dice = random.nextInt(6) + 1;
        lbl_zarDurumu.setText("Zar sonucu: " + dice);

        // LinkedList'te ilerle
        for (int i = 0; i < dice && current.next != null; i++) {
            current = current.next;
        }

        // Hücre tipine göre puan güncelle
        if (current.cellType.equals("treasure")) {
            score += 10;
            JOptionPane.showMessageDialog(this, "Hazine! +10 puan");
        } else if (current.cellType.equals("trap")) {
            score -= 5;
            JOptionPane.showMessageDialog(this, "Tuzak! -5 puan");
        } else {
            JOptionPane.showMessageDialog(this, "Boş hücre. Puan yok.");
        }

        // Yeni konumu vurgula
        current.button.setBackground(java.awt.Color.GREEN);
        lbl_score.setText("Puan: " + score);

        // Oyun bitti mi?
        if (current.next == null) {
            JOptionPane.showMessageDialog(this, "Oyun bitti! Toplam puan: " + score);
            // Skoru kaydetmek istersen:
            FileManager.saveScore(username, "level1", score);
            // Level2'ye geçmek istersen:
            new levels2(username).setVisible(true);
            this.dispose();
        }
    }//GEN-LAST:event_btn_rollDiceActionPerformed

